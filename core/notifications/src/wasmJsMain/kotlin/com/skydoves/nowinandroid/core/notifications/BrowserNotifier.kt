package com.skydoves.nowinandroid.core.notifications

import dev.zacsweers.metro.AppScope
import dev.zacsweers.metro.ContributesBinding
import dev.zacsweers.metro.Inject
import dev.zacsweers.metro.SingleIn

/**
 * Web Notifications need an explicit permission prompt, which is not something a demo should raise
 * on load, so the browser build drops notifications rather than asking. [NoOpNotifier] already
 * describes that behaviour; this only contributes it to the graph.
 */
@Inject
@SingleIn(AppScope::class)
@ContributesBinding(AppScope::class)
class BrowserNotifier : Notifier by NoOpNotifier()
